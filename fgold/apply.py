"""plan --apply: validate plan/draft.json and write PlanData.lua (design.md 2, 3.5).

Validation:
* only the keys of design.md section 2; unknown keys are rejected
* money fields are non-negative integers, duration in {1, 2, 3}, ids positive ints
* post.floorUnit/startUnit rounded UP to whole silver when the newest session
  reports copperOK == false
* buy.maxUnit <= 1.5 x ref[id].mkt unless flip == true (then <= vendor sell)
* sum(qty x maxUnit) <= budget.spendCap
* at most max_rows rows per list, notes/steps <= 5
* the rendered Lua re-parses with luasv to the same data
The draft is also checked against what it cannot change (the caps above are
only as good as ref and the budget, so a consistent edit of all three must
not pass): ref equals the stored scan basedOnScan names, budget.principal is
the config nest egg, spendCap <= gold minus the nest egg, and nothing is
added or raised compared with the draft brief generated (plan/draft.orig.json).
Then a new id YYYYMMDD-HHMM-<4 hex of content hash> (CT clock) and an atomic
write (temp file + replace, retried on PermissionError) into every root's
Interface/AddOns/ForeverGold/ and the repo addon folder. A root whose addon
folder is a link to somewhere other than the repo addon folder is skipped.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

from . import ct, luasv, util
from . import market as mk

HEADER = "-- Generated by fgold. Do not edit; change plan/draft.json and run: python -m fgold plan --apply\n"
GLOBAL = "ForeverGoldPlan"
EM_DASH = "\u2014"

TOP_KEYS = ("schema", "id", "generatedAt", "basedOnScan", "lastScanAt", "expectPriorSessions", "settings",
            "headline", "notes", "steps", "budget", "buy", "craft", "post", "hold", "vendor", "ref")
SUB_KEYS = {
    "basedOnScan": ("at", "market", "rows"),
    "settings": ("postMode", "undercut"),
    "budget": ("spendCap", "principal"),
}
ROW_KEYS = {
    "buy": ("id", "name", "qty", "maxUnit", "why", "flip"),
    "craft": ("recipe", "name", "out", "count", "profitEach", "why"),
    "post": ("id", "name", "qty", "floorUnit", "startUnit", "duration", "why"),
    "hold": ("id", "name", "why"),
    "vendor": ("id", "name", "why"),
}
ROW_REQUIRED = {
    "buy": ("id", "name", "qty", "maxUnit"),
    "craft": ("recipe", "name", "out", "count", "profitEach"),
    "post": ("id", "name", "qty", "floorUnit", "startUnit", "duration"),
    "hold": ("id", "name"),
    "vendor": ("id", "name"),
}
REF_KEYS = ("min", "mkt", "q")
MONEY = {"maxUnit", "floorUnit", "startUnit", "profitEach", "spendCap", "principal", "undercut", "min", "mkt"}
POSITIVE_COUNT = {"qty", "count"}
IDS = {"id", "recipe", "out"}
MAX_TEXT = 5


class PlanError(Exception):
    def __init__(self, problems):
        self.problems = list(problems)
        super().__init__("; ".join(self.problems))


@dataclass
class ApplyResult:
    plan: dict
    text: str
    written: list = field(default_factory=list)   # [(label, path)]
    skipped: list = field(default_factory=list)   # [(label, reason)]
    warnings: list = field(default_factory=list)
    reached: list = field(default_factory=list)   # WoW root names whose addon folder now holds the plan


def _is_int(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def ref_from_scan(scan) -> dict:
    """{itemID: {"min", "mkt", "q"}} for a stored scan: what brief copies into ref."""
    return {iid: {"min": st["min"], "mkt": st["mkt"], "q": st["q"]} for iid, st in mk.scan_stats(scan).items()}


def _check_generated(draft: dict, gen: dict, errs: list) -> None:
    """The skill's editing rules against the draft brief generated: rewrite text, delete rows,
    lower qty / count / maxUnit / spendCap, change a duration, move a post row to hold.
    Everything else stays as generated."""
    def fix(where, what):
        errs.append(f"{where}: {what} (plan/draft.orig.json is the draft as brief made it). "
                    f"Fix: undo the edit, or re-run `python -m fgold brief`")

    for k in ("schema", "basedOnScan", "lastScanAt", "expectPriorSessions", "settings", "ref"):
        if draft.get(k) != gen.get(k):
            fix(k, "changed; it is never edited")
    budget, gbudget = draft.get("budget"), gen.get("budget")
    if isinstance(budget, dict) and isinstance(gbudget, dict):
        if budget.get("principal") != gbudget.get("principal"):
            fix("budget.principal", "changed; it is never edited")
        cap, gcap = budget.get("spendCap"), gbudget.get("spendCap")
        if _is_int(cap) and _is_int(gcap) and cap > gcap:
            fix("budget.spendCap", f"raised from {gcap} to {cap}; it may only be lowered")

    def rows(obj, lst):
        v = obj.get(lst)
        return [r for r in v if isinstance(r, dict)] if isinstance(v, list) else []

    def key_of(lst, r):
        if lst == "craft":
            k = r.get("recipe")
        else:
            k = r.get("id")
        if not _is_int(k):
            return None
        return (k, bool(r.get("flip"))) if lst == "buy" else k

    limits = {"buy": ("qty", "maxUnit"), "craft": ("count",), "post": ("qty",)}
    same = {"buy": ("name",), "craft": ("name", "out", "profitEach"), "post": ("name", "floorUnit", "startUnit"),
            "hold": ("name",), "vendor": ("name",)}
    gen_rows = {lst: {key_of(lst, r): r for r in rows(gen, lst) if key_of(lst, r) is not None} for lst in same}
    for lst in same:
        used = set()
        for i, r in enumerate(rows(draft, lst), 1):
            k = key_of(lst, r)
            if k is None:
                continue
            where = f"{lst}[{i}] ({r.get('name')})"
            g = gen_rows[lst].get(k)
            if g is None and lst == "hold":
                g = gen_rows["post"].get(k)   # a post row moved to hold
            if g is None:
                fix(where, "not in the generated draft; rows are only deleted, never added"
                    + (" (flip changed?)" if lst == "buy" else ""))
                continue
            if k in used:
                fix(where, "appears twice")
                continue
            used.add(k)
            for f in same[lst]:
                if r.get(f) != g.get(f):
                    fix(where, f"{f} changed from {g.get(f)!r} to {r.get(f)!r}; it is never edited")
            for f in limits.get(lst, ()):
                if _is_int(r.get(f)) and _is_int(g.get(f)) and r[f] > g[f]:
                    fix(where, f"{f} raised from {g[f]} to {r[f]}; it may only be lowered")


def validate(draft, static=None, max_rows: int = 25, copper_ok=None, gold=None, nest=None, market_ref=None,
             generated=None):
    """Return (plan ready for Lua, warnings). Raises PlanError listing every problem.

    The checks below the spec's list need data the draft cannot carry, so callers pass them:
    gold (copper the paying account holds), nest (config nest_egg_copper), market_ref
    (ref_from_scan of the stored scan basedOnScan names; {} when that scan is not stored) and
    generated (the draft brief wrote, plan/draft.orig.json). None skips a check."""
    errs = []
    warns = []
    if not isinstance(draft, dict):
        raise PlanError(["the draft must be a JSON object"])

    for k in draft:
        if k not in TOP_KEYS:
            errs.append(f"unknown key {k!r} (allowed: {', '.join(TOP_KEYS)})")

    def money(where, v):
        if not _is_int(v):
            errs.append(f"{where} must be a whole number of copper (got {v!r})")
            return False
        if v < 0:
            errs.append(f"{where} must be >= 0 (got {v})")
            return False
        return True

    def nonneg(where, v):
        if not _is_int(v) or v < 0:
            errs.append(f"{where} must be a whole number >= 0 (got {v!r})")
            return False
        return True

    def text(where, v, required=False):
        if v is None and not required:
            return ""
        if not isinstance(v, str) or (required and not v.strip()):
            errs.append(f"{where} must be {'a non-empty ' if required else 'a '}string (got {v!r})")
            return ""
        if EM_DASH in v:
            errs.append(f"{where} contains an em-dash (U+2014): rewrite it with a colon, comma or parentheses")
        if "|" in v and where not in ("id", "basedOnScan.market"):
            warns.append(f"{where} contains '|', which WoW reads as an escape code: use '/' instead")
        if "\x00" in v:
            errs.append(f"{where} contains a NUL character")
        return v

    plan = {}
    schema = draft.get("schema")
    if schema != 1 or not _is_int(schema):
        errs.append(f"schema must be 1 (got {schema!r})")
    plan["schema"] = 1
    plan["id"] = text("id", draft.get("id")) or "draft"
    for k in ("generatedAt", "lastScanAt", "expectPriorSessions"):
        v = draft.get(k, 0)
        if nonneg(k, v):
            plan[k] = v

    for sub, keys in SUB_KEYS.items():
        v = draft.get(sub)
        if v is None and sub != "budget":
            v = {}
        if not isinstance(v, dict):
            errs.append(f"{sub} must be an object with {', '.join(keys)}" + (" (required)" if sub == "budget" else ""))
            continue
        for k in v:
            if k not in keys:
                errs.append(f"{sub}: unknown key {k!r} (allowed: {', '.join(keys)})")
        out = {}
        if sub == "basedOnScan":
            out["at"] = v.get("at", 0)
            nonneg("basedOnScan.at", out["at"])
            out["market"] = text("basedOnScan.market", v.get("market", ""))
            out["rows"] = v.get("rows", 0)
            nonneg("basedOnScan.rows", out["rows"])
        elif sub == "settings":
            pm = v.get("postMode", "match")
            if pm not in ("match", "undercut"):
                errs.append(f"settings.postMode must be \"match\" or \"undercut\" (got {pm!r})")
            out["postMode"] = pm
            out["undercut"] = v.get("undercut", 0)
            money("settings.undercut", out["undercut"])
        else:
            for k in keys:
                if k not in v:
                    errs.append(f"budget.{k} is required")
                else:
                    money(f"budget.{k}", v[k])
                    out[k] = v[k]
        plan[sub] = out

    plan["headline"] = text("headline", draft.get("headline", ""))
    for k in ("notes", "steps"):
        v = draft.get(k, [])
        if not isinstance(v, list):
            errs.append(f"{k} must be a list of strings")
            v = []
        if len(v) > MAX_TEXT:
            errs.append(f"{k} has {len(v)} entries (max {MAX_TEXT})")
        plan[k] = [text(f"{k}[{i}]", s, required=True) for i, s in enumerate(v, 1)]

    # ref first (buy rows are checked against it)
    ref = {}
    raw_ref = draft.get("ref", {})
    if not isinstance(raw_ref, dict):
        errs.append("ref must be an object of {\"<itemID>\": {\"min\", \"mkt\", \"q\"}}")
        raw_ref = {}
    for k, v in raw_ref.items():
        iid = None
        if _is_int(k):
            iid = k
        elif isinstance(k, str) and k.isascii() and k.isdigit():
            iid = int(k)
        if iid is None or iid <= 0:
            errs.append(f"ref key {k!r} must be a positive item id")
            continue
        if not isinstance(v, dict):
            errs.append(f"ref[{k}] must be an object with min, mkt, q")
            continue
        for kk in v:
            if kk not in REF_KEYS:
                errs.append(f"ref[{k}]: unknown key {kk!r} (allowed: min, mkt, q)")
        entry = {}
        for kk in REF_KEYS:
            if kk not in v:
                errs.append(f"ref[{k}].{kk} is required")
                continue
            ok = money(f"ref[{k}].{kk}", v[kk]) if kk in MONEY else nonneg(f"ref[{k}].{kk}", v[kk])
            if ok:
                entry[kk] = v[kk]
        ref[iid] = entry

    for lst, keys in ROW_KEYS.items():
        rows = draft.get(lst, [])
        if not isinstance(rows, list):
            errs.append(f"{lst} must be a list")
            rows = []
        if len(rows) > max_rows:
            errs.append(f"{lst} has {len(rows)} rows (max_rows is {max_rows})")
        out_rows = []
        for i, r in enumerate(rows, 1):
            where = f"{lst}[{i}]"
            if not isinstance(r, dict):
                errs.append(f"{where} must be an object")
                continue
            if isinstance(r.get("name"), str):
                where = f"{where} ({r['name']})"
            for k in r:
                if k not in keys:
                    errs.append(f"{where}: unknown key {k!r} (allowed: {', '.join(keys)})")
            for k in ROW_REQUIRED[lst]:
                if k not in r:
                    errs.append(f"{where}: {k} is required")
            row = {}
            for k in keys:
                if k not in r:
                    continue
                v = r[k]
                if k in IDS:
                    if not _is_int(v) or v <= 0:
                        errs.append(f"{where}: {k} must be a positive integer id (got {v!r})")
                elif k in MONEY:
                    money(f"{where}: {k}", v)
                elif k in POSITIVE_COUNT:
                    if not _is_int(v) or v <= 0:
                        errs.append(f"{where}: {k} must be a whole number >= 1 (got {v!r})")
                elif k == "duration":
                    if not _is_int(v) or v not in (1, 2, 3):
                        errs.append(f"{where}: duration must be 1 (2h), 2 (8h) or 3 (24h) (got {v!r})")
                elif k == "flip":
                    if not isinstance(v, bool):
                        errs.append(f"{where}: flip must be true or false (got {v!r})")
                elif k == "name":
                    v = text(f"{where}: name", v, required=True)
                elif k == "why":
                    v = text(f"{where}: why", v)
                row[k] = v
            if lst == "buy":
                row.setdefault("flip", False)
            if "why" in keys:
                row.setdefault("why", "")
            out_rows.append(row)
        plan[lst] = out_rows
    plan["ref"] = ref

    if copper_ok is False:
        for r in plan["post"]:
            for k in ("floorUnit", "startUnit"):
                if _is_int(r.get(k)):
                    r[k] = util.ceil_silver(r[k])

    for i, r in enumerate(plan["post"], 1):
        if _is_int(r.get("floorUnit")) and _is_int(r.get("startUnit")) and r["startUnit"] < r["floorUnit"]:
            errs.append(f"post[{i}] ({r.get('name')}): startUnit {r['startUnit']} is below floorUnit {r['floorUnit']}")

    total = 0
    for i, r in enumerate(plan["buy"], 1):
        mu, qty, iid = r.get("maxUnit"), r.get("qty"), r.get("id")
        if not (_is_int(mu) and _is_int(qty) and _is_int(iid)):
            continue
        total += qty * mu
        where = f"buy[{i}] ({r.get('name')})"
        if r.get("flip"):
            sell = static.sell(iid) if static is not None else 0
            if sell <= 0:
                errs.append(f"{where}: flip = true but the item has no known vendor sell price")
            elif mu > sell:
                errs.append(f"{where}: flip maxUnit {mu} is above the vendor sell price {sell}")
        else:
            entry = ref.get(iid)
            if not entry or "mkt" not in entry:
                errs.append(f"{where}: no ref[{iid}].mkt to check maxUnit against (add it, or drop the row)")
            elif mu > 1.5 * entry["mkt"]:
                errs.append(f"{where}: maxUnit {mu} is above 1.5 x ref mkt {entry['mkt']} "
                            f"(max {int(1.5 * entry['mkt'])})")
    cap = plan.get("budget", {}).get("spendCap")
    principal = plan.get("budget", {}).get("principal")
    if _is_int(cap) and total > cap:
        errs.append(f"buy rows need {util.fmt_money(total)} (sum of qty x maxUnit) but budget.spendCap is "
                    f"{util.fmt_money(cap)}: drop the lowest-profit rows or lower qty")
    if nest is not None and _is_int(principal) and principal != nest:
        errs.append(f"budget.principal {principal} is not the nest egg in config.local.json ({nest}); it is "
                    f"never edited. Fix: re-run `python -m fgold brief`")
    basis = nest if nest is not None else principal
    if gold is not None and _is_int(cap) and _is_int(basis) and cap > max(0, gold - basis):
        errs.append(f"budget.spendCap {util.fmt_money(cap)} is above the gold over the nest egg "
                    f"({util.fmt_money(max(0, gold - basis))}): only profit is spent. Fix: lower spendCap, or "
                    f"re-run `python -m fgold brief`")
    if market_ref is not None and ref:
        bos = plan.get("basedOnScan") or {}
        if not market_ref:
            errs.append(f"ref has prices but basedOnScan ({bos.get('market')!r} at {bos.get('at')}) is not a scan in "
                        f"the data store, and ref is copied from that scan. Fix: re-run `python -m fgold brief`")
        else:
            for iid in sorted(ref):
                if ref[iid] != market_ref.get(iid):
                    errs.append(f"ref[{iid}] {ref[iid]} does not match the stored scan ({market_ref.get(iid)}): ref "
                                f"is copied from the scan and never edited. Fix: re-run `python -m fgold brief`")
    if generated is not None:
        if isinstance(generated, dict):
            _check_generated(draft, generated, errs)
        else:
            errs.append("plan/draft.orig.json is not a JSON object. Fix: re-run `python -m fgold brief`")
    if errs:
        raise PlanError(errs)
    return plan, warns


def content_hash(plan: dict) -> str:
    body = {k: v for k, v in plan.items() if k not in ("id", "generatedAt")}
    raw = json.dumps(_jsonable(body), sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def new_id(plan: dict, now) -> str:
    return f"{ct.stamp_ct(now)}-{content_hash(plan)[:4]}"


def _jsonable(v):
    if isinstance(v, dict):
        return {str(k): _jsonable(x) for k, x in v.items()}
    if isinstance(v, list):
        return [_jsonable(x) for x in v]
    return v


def render(plan: dict) -> str:
    return HEADER + luasv.dump(GLOBAL, plan)


def check_roundtrip(plan: dict, text: str) -> None:
    try:
        back = luasv.loads(text).get(GLOBAL)
    except luasv.LuaSVError as exc:
        raise PlanError([f"internal: rendered PlanData.lua does not parse ({exc})"]) from exc
    if back != luasv.canonical(plan):
        raise PlanError(["internal: rendered PlanData.lua does not re-parse to the same data"])


_same_dir = util.same_dir


def targets(roots, addon_dir):
    """[(label, PlanData.lua path)] for installed roots + the repo copy, deduped; plus skips.

    A root whose addon folder is a link (symlink or junction) to somewhere other than the repo
    addon folder is skipped, as install and doctor refuse it: writing through it would put
    PlanData.lua into whatever folder the link points at."""
    out, skipped = [], []
    dirs = []
    for root in roots:
        d = root.addon_dir
        if not root.exists:
            skipped.append((root.name, f"WoW root not found: {root.raw}"))
            continue
        if not d.is_dir():
            skipped.append((root.name, f"addon not installed in {d}. Fix: python -m fgold install"))
            continue
        if addon_dir is not None and util.is_link(d) and not _same_dir(d, addon_dir):
            skipped.append((root.name, f"{d} is a link to somewhere other than {addon_dir} (doctor shows it as "
                                       f"broken). Fix: delete that link (not the folder it points to), then run "
                                       f"`python -m fgold install`"))
            continue
        dirs.append((root.name, d))
    if addon_dir is not None and Path(addon_dir).is_dir():
        dirs.append(("repo", Path(addon_dir)))
    elif addon_dir is not None:
        skipped.append(("repo", f"repo addon folder missing: {addon_dir}"))
    seen = []
    for label, d in dirs:
        dup = next((lab for lab, sd in seen if _same_dir(d, sd)), None)
        if dup:
            skipped.append((label, f"same folder as {dup} (linked install), written once"))
            continue
        seen.append((label, d))
        out.append((label, d / "PlanData.lua"))
    return out, skipped


def apply_draft(draft: dict, roots, addon_dir, static=None, max_rows: int = 25, copper_ok=None, gold=None,
                now=None, dry_run: bool = False, nest=None, market_ref=None, generated=None) -> ApplyResult:
    import time as _time

    now = int(now if now is not None else _time.time())
    plan, warns = validate(draft, static=static, max_rows=max_rows, copper_ok=copper_ok, gold=gold, nest=nest,
                           market_ref=market_ref, generated=generated)
    plan["generatedAt"] = now
    plan["id"] = new_id(plan, now)
    text = render(plan)
    check_roundtrip(plan, text)
    res = ApplyResult(plan=plan, text=text, warnings=warns)
    tgts, res.skipped = targets(roots, addon_dir)
    if dry_run:
        return res
    for label, path in tgts:
        try:
            util.write_text_atomic(path, text)
        except OSError as exc:
            res.skipped.append((label, f"write failed: {exc}. Fix: close the file in other programs and retry"))
            continue
        if Path(path).read_text(encoding="utf-8") != text:
            res.skipped.append((label, "read-back after write did not match"))
            continue
        res.written.append((label, path))
    folders = [Path(p).parent for _, p in res.written]
    for root in roots:
        if root.exists and any(_same_dir(root.addon_dir, f) for f in folders):
            res.reached.append(root.name)
    return res


def plan_to_json(plan: dict) -> dict:
    """The applied plan in draft.json shape (ref keys as strings)."""
    out = dict(plan)
    out["ref"] = {str(k): v for k, v in sorted(plan.get("ref", {}).items())}
    return out
